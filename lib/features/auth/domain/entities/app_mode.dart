/// Режим приложения: что показывать вошедшему пользователю.
///
/// Определяется ролями из `GET /auth/me`, а не способом входа и не тем, какое
/// приложение открыто (`docs/ARCHITECTURE.md`, раздел 5).
enum AppMode {
  /// Клиентский поток: онбординг и главный экран.
  client,

  /// Тренер: пока только экран со ссылкой на веб-кабинет.
  trainer,

  /// Администратор: пока только пояснение, что администрирование — в вебе.
  admin,
}
